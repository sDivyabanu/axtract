"""Formulas inside prose lines of scanned pages: locate the formula tokens so the recognizer can read them."""
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from services.scanned_math import prose_math_run


def span(text):
    tokens = text.split()
    run = prose_math_run(tokens)
    return None if run is None else " ".join(tokens[run[0]:run[1] + 1])


@pytest.mark.parametrize("line,expected", [
    ("Find the volume generated by revolving about the line y = x the part of", "y = x"),
    ("Find the volume generated by revolving about x = a the part of", "x = a"),
    ("about y = — 2 a the", "y = — 2 a"),
    ("bounded by the coordinate axes and the parabola x* + y* = a5", "x* + y* = a5"),
    ("the cardioid r = a (1 +", "r = a (1 +"),
])
def test_the_formula_inside_a_prose_line_is_located(line, expected):
    assert span(line) == expected


@pytest.mark.parametrize("line", ["Find the volume generated by revolving the ellipse", "Divide the solid into slices", "1. Introduction"])
def test_prose_without_an_equals_sign_has_no_formula(line):
    assert span(line) is None


def test_ordinary_words_end_the_formula_run():
    assert span("the equation holds whenever x = 2 and therefore the result follows") == "x = 2"
